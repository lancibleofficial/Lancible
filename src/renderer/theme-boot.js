/* Тема — до первой отрисовки. Подключается в <head>, раньше всего остального.
 *
 * Тема, выбранная руками, живёт в state.settings.theme, а state приходит
 * только после init() в app.js: на десктопе — из файла через IPC, в вебе — из
 * хранилища шима. До этого страница (и скелетон загрузки) шла за системной
 * темой: при выбранной светлой и тёмной ОС скелетон мелькал тёмным, и
 * наоборот. Поэтому applyTheme() дублирует выбор в localStorage, а этот файл
 * читает его синхронно, пока ничего не нарисовано.
 *
 * Отдельным файлом, а не строкой в <head>: политика безопасности страницы
 * (script-src 'self') встроенных скриптов не пускает. */
(function () {
  try {
    const theme = localStorage.getItem('lancible.theme');
    if (theme === 'light' || theme === 'dark') document.documentElement.setAttribute('data-theme', theme);
  } catch (e) { /* хранилище закрыто — остаётся системная тема */ }
}());
