-- Lancible — вложения в журнале ИИ-агента (Edge Function ai-chat), круг 20.
-- Выполнить один раз: Supabase Dashboard → SQL Editor → New query → вставить
-- целиком → Run. Повторный запуск безопасен: «add column if not exists».
-- Нужна таблица ai_calls (supabase/ai.sql).
--
-- Что добавляется. С 18 октября 2026 к сообщению агенту можно приложить
-- изображения, PDF и текстовые файлы. Сами файлы нигде не хранятся — ни в
-- данных, ни в синхронизации, ни в хранилище: функция проверяет их и
-- передаёт модели в том же вызове. В журнал ложится только счёт:
--   attachments  — сколько вложений ушло модели в этом вызове;
--   attach_bytes — их общий размер в байтах (изображения — после
--                  перекодировки на устройстве, текст — в UTF-8).
-- Ни имён файлов, ни содержимого здесь нет и не будет (privacy.html, §11).
--
-- Порядок не важен: функция пишет эти поля отдельной правкой после строки
-- вызова, и без колонок правка просто не проходит — вызов отвечает как
-- обычно. Выполнить можно до выкладки новой функции или после.

alter table ai_calls add column if not exists attachments integer not null default 0;
alter table ai_calls add column if not exists attach_bytes integer not null default 0;
