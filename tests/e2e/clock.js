// Прибитые часы для браузерных тестов. Запуск: npm run test:e2e
//
// Зачем. Календарь показывает неделю с понедельника, и тест, который сеет
// срок «на завтра» и ждёт его в этой же неделе, проходит шесть дней из семи:
// в воскресенье завтра — уже следующая неделя. Ровно так и падали
// agenda.spec «неделя: семь столбцов» и repeat.spec «призраки», и падали
// молча — раз в неделю, в день, когда на сборку никто не смотрит.
//
// Лечить это правкой ожиданий нельзя: «двух сроков в неделе» тест и должен
// ждать. Лечится источником — временем, которое видит страница.
//
// Почему именно эта дата. Среда: от неё и «вчера», и «завтра» остаются внутри
// одной недели. Десятое число: ни начало месяца, ни конец, так что сдвиги на
// пару дней не перепрыгивают через границу месяца. Полдень: сутки не
// переворачиваются от смещения на час.
//
// Литерал без «Z» — местное время, а не UTC. Это важно: неделю приложение
// режет по местной полуночи, и на машине в UTC+5 и на раннере в UTC должна
// получаться одна и та же среда, а не разные дни.
const ANCHOR = '2026-06-10T12:00:00';

/** Прибить время страницы к ANCHOR. Звать ДО page.goto: приложение читает
 *  текущее время при загрузке, и после перехода подменять уже поздно.
 *
 *  setFixedTime, а не install: нужна только неподвижная дата, а таймеры
 *  пусть идут настоящие — на них держится отсчёт работающего таймера. */
async function pinClock(page) {
  await page.clock.setFixedTime(new Date(ANCHOR));
}

module.exports = { ANCHOR, pinClock };
