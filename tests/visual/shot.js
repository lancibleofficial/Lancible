// Снимки с эталоном: сравнение и правило «нет эталона — скажи вслух».
//
// Почему не просто toHaveScreenshot. Эталон привязан к системе: Chromium на
// Windows и на Linux рисует текст по-разному, и один и тот же экран даёт
// разные пиксели. Playwright это понимает и кладёт эталоны с суффиксом
// платформы, но из этого следует неприятное: на машине, где эталона для её
// системы ещё нет, тест падает не потому, что что-то сломалось, а потому что
// сравнивать не с чем.
//
// Молча пропускать такой тест нельзя — он станет вечнозелёным и перестанет
// что-либо значить. Поэтому здесь он пропускается ГРОМКО: с причиной и
// командой, которой эталон создаётся. Это тот же приём, что `{ todo: ... }` в
// юнитах: недоработка помечена в наборе, а не спрятана.
//
// Завести эталоны для своей системы:  npm run test:visual:update
const fs = require('node:fs');
const { expect } = require('@playwright/test');

/** Сравнить с эталоном. `target` — страница целиком или отдельный элемент
 *  (локатор). При отсутствии эталона — пропуск с причиной. */
async function expectShot(target, test, name, options = {}) {
  const info = test.info();
  const file = info.snapshotPath(name);
  // При обычном прогоне отсутствие эталона — повод пропустить. При прогоне
  // через npm run test:visual:update эталон как раз и создаётся.
  //
  // Признак — переменная окружения, а не config.updateSnapshots. На него я
  // уже наступил: по умолчанию он 'missing', то есть «пиши недостающие и
  // считай тест упавшим», и условие «не none — значит создаём» пропускало
  // вперёд обычный прогон. На GitHub из-за этого покраснели все 22 снимка
  // вместо того, чтобы пропуститься.
  const updating = process.env.LANCIBLE_SNAPSHOTS === 'update';
  if (!updating && !fs.existsSync(file)) {
    test.skip(true,
      `эталона для этой системы нет (${file}). Завести: npm run test:visual:update`);
    return;
  }
  await expect(target).toHaveScreenshot(name, {
    // Сглаживание шрифтов даёт единицы отличающихся пикселей на букву даже
    // между двумя прогонами на одной машине. Порог отсекает этот шум и
    // оставляет настоящие сдвиги вёрстки.
    maxDiffPixelRatio: 0.01,
    animations: 'disabled',
    caret: 'hide',
    ...options,
  });
}

module.exports = { expectShot };
