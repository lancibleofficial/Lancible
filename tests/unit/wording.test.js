// Слова интерфейса: одно понятие — одно слово, одно обращение. Запуск: npm run test:unit
//
// Откуда взялось. Словари десктопа и телефона разные по делу — у телефона
// свои экраны и строки короче, — и из-за этого они разошлись не только в
// длине. Один и тот же дедлайн назывался «сроком» на десктопе и «дедлайном»
// на телефоне; в одном окне приложение обращалось на «вы», в соседнем на
// «ты». Ни один тест этого не ловил и не мог: словарям различаться
// разрешено.
//
// Решение пользователя: «дедлайн» и «вы». Здесь оно записано кодом, потому
// что словами в документе оно не удержится — ключей больше семисот на обе
// платформы, и каждый новый пишется по памяти.
//
// Почему проверка только для русского и украинского. В английском различия
// «ты/вы» нет. В казахском словаре повелительное наклонение неформальное
// последовательно, во всех строках без исключения; менять это — отдельное
// решение, и принимать его должен тот, кто читает по-казахски.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const CoreLang = require('../../src/renderer/core/lang.js');
const DESKTOP = require('../../src/renderer/core/i18n.js').T;

/** Словарь телефона — ES-модуль, читаем его так же, как соседние тесты. */
const MOBILE = (() => {
  const file = path.join(__dirname, '..', '..', 'mobile', 'src', 'lib', 'i18n.js');
  const src = fs.readFileSync(file, 'utf8')
    .replace(/^import[\s\S]*?from '[^']+';$/gm, '')
    .replace(/^export /gm, '');
  const box = {};
  // eslint-disable-next-line no-new-func
  new Function('module', 'Lang', `${src};module.exports = { T };`)(box, CoreLang);
  return box.exports.T;
})();

const DICTS = [['десктоп', DESKTOP], ['телефон', MOBILE]];

/** Границы слова для кириллицы. \b в JS опирается на \w, а тот знает только
 *  латиницу: `\bты\b` в русской строке не сработает никогда. */
const LETTERS = "а-яёА-ЯЁіїєІЇЄәғқңөұүһӘҒҚҢӨҰҮҺ'"; // русские, украинские, казахские
const word = (list) => new RegExp(
  `(^|[^${LETTERS}])(${list.join('|')})([^${LETTERS}]|$)`,
  'i',
);

const strings = (dict, lang) => Object.entries(dict[lang] || {})
  .flatMap(([k, v]) => (Array.isArray(v) ? v.map((x) => [k, x]) : [[k, v]]));

// --- одно понятие — одно слово ----------------------------------------------

test('дедлайн называется дедлайном, а не сроком', () => {
  // «Срок» остался только в одном словаре из восьми — русском десктопном, —
  // и выглядело это так: на компьютере «Убрать срок», на телефоне «Убрать
  // дедлайн», одна и та же кнопка.
  const re = word(['срок', 'срока', 'сроку', 'сроком', 'сроки', 'сроков', 'срокам']);
  const bad = [];
  for (const [who, dict] of DICTS) {
    for (const [key, s] of strings(dict, 'ru')) {
      if (re.test(String(s))) bad.push(`${who} ru / ${key}: ${JSON.stringify(s)}`);
    }
  }
  assert.deepEqual(bad, [], 'выбрано слово «дедлайн»');
});

// --- одно обращение ---------------------------------------------------------

const INFORMAL = {
  ru: ['ты', 'тебе', 'тебя', 'тобой', 'твой', 'твоя', 'твоё', 'твои',
    'нажми', 'введи', 'выбери', 'укажи', 'войди', 'открой', 'проверь',
    'попробуй', 'добавь', 'убери', 'задай', 'посмотри', 'создай', 'начни'],
  uk: ['ти', 'тобі', 'тебе', 'твій', 'твоя', 'твоє', 'твої',
    'натисни', 'введи', 'обери', 'вибери', 'вкажи', 'увійди', 'відкрий',
    'перевір', 'спробуй', 'додай', 'прибери', 'подивись', 'створи', 'почни'],
  // Казахский — с 10 октября 2026 на «сіз»: пользователь выбрал вежливую
  // форму. Неформальное — местоимение «сен» в падежах и повеление голой
  // основой глагола («таңда»); вежливое — «сіз» и «-ыңыз/-іңіз»
  // («таңдаңыз»), его список не ловит. «қара» (и «смотри», и «чёрный») и
  // «тарт» в список не взяты: слишком много невинных совпадений.
  kk: ['сен', 'сені', 'саған', 'сенің', 'сенде', 'сенен', 'сенімен',
    'бас', 'таңда', 'енгіз', 'аш', 'тексер', 'қос', 'жаса', 'құр', 'баста',
    'кір', 'жой', 'сақта', 'көрсет', 'өзгерт', 'жүкте', 'жап', 'көр',
    'қайтала', 'жаз', 'шық'],
};

/** Устойчивые сочетания, где форма совпадает с повелением, но им не
 *  является: «Бас тарту» — «отказаться» (кнопка «Отмена»), а не «нажми». */
const NOT_IMPERATIVE = {
  kk: [/бас\s+тарт[а-яёәғқңөұүһі]*/gi],
};
const clean = (lang, s) => (NOT_IMPERATIVE[lang] || []).reduce((acc, re) => acc.replace(re, ' '), String(s));

const POLITE = { ru: '«вы»', uk: '«ви»', kk: '«сіз»' };

for (const lang of Object.keys(INFORMAL)) {
  test(`приложение обращается на ${POLITE[lang]} (${lang})`, () => {
    const re = word(INFORMAL[lang]);
    const bad = [];
    for (const [who, dict] of DICTS) {
      for (const [key, s] of strings(dict, lang)) {
        if (re.test(clean(lang, s))) bad.push(`${who} ${lang} / ${key}: ${JSON.stringify(s)}`);
      }
    }
    assert.deepEqual(bad, [], `выбрано обращение на ${POLITE[lang]}`);
  });
}

// --- замок ------------------------------------------------------------------

test('проверке есть что проверять', () => {
  // Если словари однажды переименуют или загрузчик сломается, тесты выше
  // станут проверять пустоту и останутся зелёными.
  assert.ok(Object.keys(DESKTOP.ru).length > 300, 'словарь десктопа не загрузился');
  assert.ok(Object.keys(MOBILE.ru).length > 200, 'словарь телефона не загрузился');
  // И сама регулярка должна срабатывать на том, что ищет.
  assert.ok(word(['нажми']).test('Нажми «+ Новая»'), 'граница слова не работает');
  assert.ok(!word(['нажми']).test('Нажмите «+ Новая»'), 'вежливая форма не должна ловиться');
  // Казахский: граница слова знает казахские буквы, вежливое не ловится,
  // «Бас тарту» не считается повелением.
  const kk = word(INFORMAL.kk);
  assert.ok(kk.test(clean('kk', '«+ Жаңа» түймесін бас.')), 'kk: «бас» не пойман');
  assert.ok(kk.test(clean('kk', 'Күнді таңда')), 'kk: «таңда» не пойман');
  assert.ok(!kk.test(clean('kk', 'Күнді таңдаңыз')), 'kk: вежливое «таңдаңыз» поймано');
  assert.ok(!kk.test(clean('kk', '«+ Жаңа» түймесін басыңыз.')), 'kk: вежливое «басыңыз» поймано');
  assert.ok(!kk.test(clean('kk', 'Бас тарту')), 'kk: «Бас тарту» принято за повеление');
  assert.ok(!kk.test(clean('kk', 'Басты бет')), 'kk: «Басты» принято за «бас»');
});
