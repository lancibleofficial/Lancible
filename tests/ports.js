// Порты для браузерных прогонов. Вынесены отдельно, чтобы конфигурация
// Playwright и сами тесты брали одно и то же число, а не держали его в двух
// местах.
//
// Почему не 5173/5174: на них живут npm run serve:web и serve:landing. Тест,
// который дерётся за порт с открытым окном разработчика, падает по причинам,
// не имеющим отношения к коду.
//
// Почему пар две. Сторож (npm run watch) гоняет те же наборы в фоне, и если
// он и ручной прогон делят порт, они мешают друг другу: Playwright поднимает
// сервер сам и гасит его, закончив, — прямо из-под соседнего прогона. Со
// стороны это выглядит как случайные падения разных тестов на разных
// запусках, и именно так оно и выглядело. Поэтому сторож ставит
// LANCIBLE_TEST_PORTS=watch и работает на своей паре.
const watching = process.env.LANCIBLE_TEST_PORTS === 'watch';

module.exports = watching
  ? { PORT_WEB: 5195, PORT_LANDING: 5194 }
  : { PORT_WEB: 5199, PORT_LANDING: 5198 };
